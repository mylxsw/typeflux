#!/usr/bin/env python3
"""Replay the helper coverage scenarios with an explicitly instrumented local binary.

Images/audio are generated by capture_media.py. Set --profiles to retain LLVM raw profiles.
This consolidates the two original foreground probes; it does not download any assets.
"""
import argparse
import importlib.util
import os
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--helper', type=Path, required=True)
parser.add_argument('--model', type=Path, required=True)
parser.add_argument('--projector', type=Path, required=True)
parser.add_argument('--media-dir', type=Path, required=True)
parser.add_argument('--profiles', type=Path, required=True)
parser.add_argument('--background', action='store_true')
args = parser.parse_args()
args.profiles.mkdir(parents=True, exist_ok=True)
flags = ['--background'] if args.background else []
if args.background: os.environ.update(VECLIB_MAXIMUM_THREADS='1', OMP_NUM_THREADS='1')
os.environ['LLVM_PROFILE_FILE'] = str(args.profiles.resolve() / 'helper-%p.profraw')
spec = importlib.util.spec_from_file_location('batch_probe', Path(__file__).with_name('measure_batch.py'))
probe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(probe)
helper, model, projector = args.helper.resolve(), args.model.resolve(), args.projector.resolve()
worker = probe.Worker([helper, model, *flags])
try:
    requests = [dict(texts=['title: notes.txt | text: '+('项目报销流程需要发票和主管批准。'*27)]*16),
                dict(texts=[]), dict(texts=['']), dict(texts=['a']*17), dict(texts=['a'*1801]),
                dict(media=dict(kind='unknown', path='/missing')), dict(media=dict(kind='audio', path='relative'))]
    for index, request in enumerate(requests):
        reply, _ = worker.request(request)
        assert ('embeddings' in reply) if index == 0 else reply.get('error'), reply
finally:
    worker.close()
for arguments in [[], ['/missing-model.gguf'], [str(model), '/missing-projector.gguf']]:
    result = subprocess.run([str(helper), *arguments], input=b'', stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    assert result.returncode != 0
worker = probe.Worker([helper, model, projector, *flags])
try:
    for kind, name, success in [('image', 'red.png', True), ('audio', 'clip-00.wav', True),
                                ('audio', 'red.png', False), ('image', 'missing.png', False)]:
        reply, _ = worker.request(dict(media=dict(kind=kind, path=str(args.media_dir.resolve()/name))))
        assert len(reply['embeddings'][0]) == 768 if success else reply.get('error'), reply
finally:
    worker.close()
print('Helper text split, real media and error scenarios passed')
