    static let validIDs = Set(ids.values)

    static func metrics(eventName: String, properties: [String: String]) -> [Int] {
        var keys: [String] = []
        if eventName.hasPrefix("dictation_session_") {
            keys.append("voice.dictation." + eventName.dropFirst("dictation_session_".count))
        }
        if let feature = properties["feature"], eventName.hasPrefix(feature + "_") {
            let event = String(eventName.dropFirst(feature.count + 1))
            keys.append(feature + ".event." + event)
            if event == "action_executed" || event == "action_triggered" {
                if let action = properties["action"] { keys.append(feature + ".action." + action) }
                if let result = properties["result_type"] { keys.append(feature + ".result." + result) }
            }
            if feature == "keyword", event == "executed", let plugin = properties["plugin_id"] {
                keys.append("keyword.plugin." + plugin)
            }
            if event == "started" {
                if feature == "screenshot", let mode = properties["capture_mode"] { keys.append("screenshot.capture." + mode) }
                if feature == "workflow" {
                    for (group, property) in [("source", "workflow_source"), ("runtime", "runtime"), ("execution", "execution_kind")] {
                        if let value = properties[property] { keys.append("workflow." + group + "." + value) }
                    }
                }
            }
        }
        return Array(Set(keys.compactMap { ids[$0] })).sorted()
    }
